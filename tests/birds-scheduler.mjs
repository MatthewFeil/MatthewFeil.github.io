import assert from 'node:assert/strict';
import {BirdScheduler} from '../assets/js/birds-scheduler.mjs';
const scheduler=new BirdScheduler();
const stable=now=>[{seen:now,motionSeen:now,motionQuality:.9,speciesId:'robin',motionLost:false}];
assert.equal(scheduler.motionFps,30);
scheduler.lastAnalysis=1000;
assert.equal(scheduler.analysisDelay(stable(1050),1050),350);
assert.equal(scheduler.analysisDelay([],1050),110);
assert.equal(scheduler.analysisDelay([{...stable(1050)[0],speciesId:null}],1050),170);
assert.equal(scheduler.analysisDelay([{...stable(1050)[0],motionLost:true}],1050),70);
scheduler.observeAnalysis(350);
for(let now=0;now<=1400;now+=100)scheduler.observeMotion(5,now,stable(now));
assert.equal(scheduler.motionFps,30,'Short pressure should not lower the target');
scheduler.observeMotion(5,1500,stable(1500));
assert.equal(scheduler.motionFps,24,'Sustained analysis pressure frees capacity');
const uncertain=[{...stable(1200)[0],speciesId:null}];
const delay=scheduler.analysisDelay(uncertain,1200);
scheduler.motionFps=30;
assert.ok(delay<scheduler.analysisDelay(uncertain,1200),'24 fps allows a higher analysis duty budget');
scheduler.motionFps=24;
for(let i=0;i<30;i++)scheduler.observeAnalysis(20);
for(let now=1600;now<6600;now+=100)scheduler.observeMotion(5,now,stable(now));
assert.equal(scheduler.motionFps,24,'Require sustained headroom before restoring 30');
scheduler.observeMotion(5,6600,stable(6600));
assert.equal(scheduler.motionFps,30);
scheduler.reset();
for(let now=0;now<=1500;now+=100)scheduler.observeMotion(29,now,stable(now));
assert.equal(scheduler.motionFps,24,'Motion overhead also triggers fallback');
scheduler.lastAnalysis=1000;scheduler.observeAnalysis(900);
assert.ok(scheduler.analysisDelay(stable(1900),1900)>0,'Slow jobs leave breathing room rather than run back-to-back');
scheduler.reset();assert.equal(scheduler.motionFps,30);assert.equal(scheduler.analysisMs,0);assert.equal(scheduler.lastAnalysis,-Infinity);
console.log('Adaptive analysis budgets, 30/24 fps pressure hysteresis, headroom recovery and lifecycle reset passed.');
